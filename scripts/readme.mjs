// Fills the generated regions of README.md from files, so numbers and links are never typed by hand:
// badges and links from docs/deploy.json, the problem table from docs/sources.json, the measured
// table from docs/FACTS.json, the Qloo table from SDK_SURFACE.md, screenshots from docs/screens/.
// Usage: node scripts/readme.mjs [--check]
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const deploy = JSON.parse(readFileSync("docs/deploy.json", "utf8"));
const sources = JSON.parse(readFileSync("docs/sources.json", "utf8"));
const facts = JSON.parse(readFileSync("docs/FACTS.json", "utf8"));
const surface = readFileSync("SDK_SURFACE.md", "utf8");
let md = readFileSync("README.md", "utf8");

const region = (name, body) => {
  const re = new RegExp(`(<!-- ${name}:start -->)[\\s\\S]*?(<!-- ${name}:end -->)`);
  if (!re.test(md)) throw new Error(`README is missing region ${name}`);
  md = md.replace(re, `$1\n${body}\n$2`);
};
const link = (label, url) => (url ? `[${label}](${url})` : `${label}: not deployed yet`);
const shot = (n) => (existsSync(`docs/screens/${n}`) ? `docs/screens/${n}` : null);

region("badges", [
  deploy.web ? `[![Live](https://img.shields.io/badge/live-open%20the%20app-E8692C)](${deploy.web})` : "",
  deploy.repo ? `[![CI](${deploy.repo}/actions/workflows/ci.yml/badge.svg)](${deploy.repo}/actions)` : "",
  "[![MIT licence](https://img.shields.io/badge/licence-MIT-5B5852)](LICENSE)",
].filter(Boolean).join(" "));

region("links", `| | |\n|---|---|\n| Live app | ${deploy.web ? link(deploy.web, deploy.web) : "not deployed yet"} |\n| For judges | ${deploy.web ? link("/judge, a 60 second walk", `${deploy.web}/judge`) : "/judge"} |\n| Sample resident | ${deploy.web ? link("/sample", `${deploy.web}/sample`) : "/sample"} |\n| Method | ${deploy.web ? link("/method", `${deploy.web}/method`) : "/method"} |\n| Evidence | [EVIDENCE.md](EVIDENCE.md) |\n| Repository | ${link(deploy.repo, deploy.repo)} |\n| Video | ${deploy.video ? link(deploy.video, deploy.video) : "not recorded yet"} |`);

region("problem", sources.sources.map((s) => `| **${s.stat}** ${s.statement} | [${s.label}](${s.url}) |`).join("\n"));

const f = (v) => (v === null || v === undefined ? "not measured yet" : `${v}%`);
const set = (label, s) => (s ? `| ${label} | ${s.cardsBuilt} of ${s.forms} | ${f(s.plainAiPassingRulesPct)} | ${f(s.plainAiOutsideYearsPct)} | ${f(s.plainAiNotInQlooPct)} | ${f(s.personalRatePct)} | ${s.meanLiveQlooCallsPerCard ?? "not measured yet"} | ${s.meanBuildSeconds ?? "not measured yet"} |` : `| ${label} | not run yet | | | | | | |`);
region("measured", `Numbers come from \`docs/FACTS.json\`, generated by \`scripts/facts.mjs\` from \`docs/eval-summary.json\`.\n\n| Set | Cards built | Plain AI passing the same rules | Plain AI outside the years | Plain AI not in Qloo | Personal items on the card | Live Qloo calls per card | Build seconds |\n|---|---|---|---|---|---|---|---|\n${set("Curated", facts.curated)}\n${set("Wild", facts.wild)}\n\nMisses recorded: ${facts.misses.length}.`);

const rows = surface.split("\n").filter((l) => l.startsWith("| ") && l.includes("](backend/")).slice(0, 17);
region("surface", `| Feature | Call site | Status | Note |\n|---|---|---|---|\n${rows.join("\n")}`);

const hero = shot("landing-desktop-1440x900.png");
region("shots-hero", hero ? `![Aftersong landing page](${hero})` : "");
const grid = ["landing-desktop-1440x900.png", "building-card.png", "session-iphone.png", "compare.png"].map(shot);
region("shots-grid", grid.every(Boolean) ? `| | |\n|---|---|\n| ![Landing](${grid[0]}) | ![Building the card](${grid[1]}) |\n| ![Session mode on a phone](${grid[2]}) | ![Compare panel](${grid[3]}) |` : "");

if (process.argv.includes("--check")) {
  if (readFileSync("README.md", "utf8") !== md) {
    console.error("README.md generated regions are out of date. Run: node scripts/readme.mjs");
    process.exit(1);
  }
  console.log("README.md is current.");
} else {
  writeFileSync("README.md", md);
  console.log("README.md regions updated.");
}
