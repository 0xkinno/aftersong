// Writes PLATFORM_PROBE.md from docs/probe-summary.json plus the dated notes in docs/probe-notes.md.
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const s = JSON.parse(readFileSync("docs/probe-summary.json", "utf8"));
const notes = existsSync("docs/probe-notes.md") ? readFileSync("docs/probe-notes.md", "utf8") : "";
const rows = s.results.map((r) => `| \`${r.id}\` | ${r.what} | ${r.ok ? "worked" : "failed"} | ${(r.note ?? "").replace(/\|/g, "/")} |`).join("\n");
const failed = s.results.filter((r) => !r.ok).length;
writeFileSync(
  "PLATFORM_PROBE.md",
  `# PLATFORM_PROBE.md (Gate G5)

Generated by \`node scripts/probe.mjs\` on ${s.at} against ${s.host} with our own key, then written by
\`node scripts/probe-doc.mjs\`. The summary holds counts and field presence only, no entity names.
${s.liveCalls} live calls. Probes that failed: ${failed} of ${s.results.length}.

| Probe | What | Result | Detail |
|---|---|---|---|
${rows}

## Decision: music era strategy

**${s.decision.musicEraStrategy}**: ${s.decision.rationale}

Rate headers seen: ${JSON.stringify(s.rateHeaders)}

${notes}
## Not probed
Harness MCP tools (used only for the equivalence check, see SDK_SURFACE.md), books, podcasts, brands, video games. \`/v2/trending\` answered but is not used by the product.
`,
);
console.log("wrote PLATFORM_PROBE.md");
