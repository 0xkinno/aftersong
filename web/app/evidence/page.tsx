import facts from "@/lib/facts.json";
import sources from "@/lib/sources.json";

export const metadata = { title: "Evidence, Aftersong" };

type SetFacts = {
  forms: number; cardsBuilt: number; cardsThin: number; aftersongItems: number; personalRatePct: number | null;
  plainAiPassingRulesPct: number | null; plainAiOutsideYearsPct: number | null; plainAiNotInQlooPct: number | null;
  meanLiveQlooCallsPerCard: number | null; meanBuildSeconds: number | null;
} | null;
type Sessions = {
  participants: number; formTarget: number; shortfall: number; recordedOn: string; sessionDate: string | null; durationMinutes: number | null;
  entries: Array<{ id: string; summary: string }>;
  humanReview: null | { reviewer: string; date: string; falseRejections: number; falseKeeps: number };
} | null;

const pct = (v: number | null | undefined) => (v === null || v === undefined ? null : `${v}%`);
const val = (v: string | null) => (v === null ? <span className="unmeasured">Not measured yet</span> : v);

export default function Evidence() {
  const F = facts as unknown as { curated: SetFacts; wild: SetFacts; sessions: Sessions; misses: Array<{ id: string; set: string; status: string; reason: string | null }> };
  const c = F.curated;
  const w = F.wild;
  const s = F.sessions;
  const row = (label: string, d: SetFacts) => (
    <tr key={label}>
      <th scope="row">{label}</th>
      <td>{d && d.forms > 0 ? `${d.cardsBuilt} of ${d.forms}` : <span className="unmeasured">No forms yet</span>}</td>
      <td>{val(pct(d?.plainAiPassingRulesPct))}</td>
      <td>{val(pct(d?.plainAiOutsideYearsPct))}</td>
      <td>{val(pct(d?.plainAiNotInQlooPct))}</td>
      <td>{val(d && d.forms > 0 ? pct(d.personalRatePct) : null)}</td>
    </tr>
  );
  return (
    <div className="wrap py-10">
      <p className="kicker">Evidence</p>
      <h1 className="text-40 md:text-64">What was measured, and what missed</h1>
      <p className="mt-3 max-w-2xl text-ink-2">Every number on this page is read from a file generated by a script from real runs. Where nothing has been measured, the page says so.</p>

      <dl className="statrow mt-8">
        <div><dt>Cards built, curated</dt><dd>{c ? `${c.cardsBuilt} of ${c.forms}` : "None"}</dd></div>
        <div><dt>Items on those cards</dt><dd>{c?.aftersongItems ?? 0}</dd></div>
        <div><dt>Personal items</dt><dd>{pct(c?.personalRatePct) ?? "Not measured yet"}</dd></div>
        <div><dt>Qloo calls per card</dt><dd>{c?.meanLiveQlooCallsPerCard ?? "Not measured yet"}</dd></div>
      </dl>

      <section className="mt-12">
        <h2 className="text-28">Against a plain AI list</h2>
        <p className="mt-2 max-w-2xl text-ink-2">The plain AI list is run through the same rules as the card. Aftersong's own checks for years and connection are enforced in code, so they hold by construction and are not offered as results.</p>
        <div tabIndex={0} role="region" aria-label="Scrollable table" className="panel mt-5 overflow-x-auto">
          <table className="tidy">
            <thead><tr><th>Set</th><th>Cards built</th><th>Plain AI passing</th><th>Outside the years</th><th>Not in Qloo</th><th>Personal items</th></tr></thead>
            <tbody>{row("Curated forms", c)}{row("Wild forms", w)}</tbody>
          </table>
        </div>
        <p className="mt-3 text-14 text-ink-2">Source: docs/FACTS.json.</p>
      </section>

      <section className="mt-12">
        <h2 className="text-28">Sessions with older people</h2>
        {s ? (
          <>
            <dl className="statrow mt-5">
              <div><dt>Participants</dt><dd>{s.participants}</dd></div>
              <div><dt>Target</dt><dd>{s.formTarget}</dd></div>
              <div><dt>Still to find</dt><dd>{s.shortfall}</dd></div>
              <div><dt>Session length</dt><dd>{s.durationMinutes === null ? "Not recorded" : `${s.durationMinutes} min`}</dd></div>
            </dl>
            <div className="grid gap-4 mt-5 md:grid-cols-3">
              {s.entries.map((e) => (
                <div key={e.id} className="panel p-5"><p className="kicker">{e.id}</p><p className="mt-2">{e.summary}</p></div>
              ))}
            </div>
            <p className="mt-4 max-w-2xl text-14 text-ink-2">Recorded {s.recordedOn}. These are the participants' own reports about ease of use. They are not a measure of benefit, and no claim of benefit is made.</p>
          </>
        ) : <p className="mt-3 text-ink-2">No session has been recorded.</p>}
      </section>

      <section className="mt-12">
        <h2 className="text-28">Both error directions</h2>
        {s?.humanReview ? (
          <dl className="statrow mt-5">
            <div><dt>Rejected, reviewer would keep</dt><dd>{s.humanReview.falseRejections}</dd></div>
            <div><dt>Kept, reviewer says wrong</dt><dd>{s.humanReview.falseKeeps}</dd></div>
            <div><dt>Reviewer</dt><dd>{s.humanReview.reviewer}</dd></div>
            <div><dt>Date</dt><dd>{s.humanReview.date}</dd></div>
          </dl>
        ) : (
          <div className="panel p-5 mt-5"><p>Not recorded yet. A human reviewer has to check both what Aftersong rejected and what it kept; the counts, reviewer and date appear here once they exist. The plain AI false positive rate is not reported until it has been measured.</p></div>
        )}
      </section>

      <section className="mt-12">
        <h2 className="text-28">Misses, by form</h2>
        {F.misses.length === 0 ? <p className="mt-3 text-ink-2">No misses recorded. Every form in the curated set built a card.</p> : (
          <div className="panel mt-5 overflow-x-auto"><table className="tidy"><thead><tr><th>Form</th><th>Set</th><th>Result</th><th>Why</th></tr></thead><tbody>{F.misses.map((m) => <tr key={m.id}><td>{m.id}</td><td>{m.set}</td><td>{m.status}</td><td>{m.reason}</td></tr>)}</tbody></table></div>
        )}
      </section>

      <section className="mt-12">
        <h2 className="text-28">Sources for the problem</h2>
        <div className="grid gap-4 mt-5 md:grid-cols-2">
          {sources.sources.map((x) => (
            <div key={x.id} className="panel p-5"><p className="kicker">{x.stat}</p><p className="mt-2">{x.statement}</p><p className="text-14 mt-3"><a className="underline" href={x.url}>{x.label}</a></p><p className="text-12 text-ink-2 mt-1">{x.verified}</p></div>
          ))}
        </div>
      </section>
      <p className="mt-10 text-14 text-ink-2">Full evidence file, disclosures and reproduction commands are in the repository: EVIDENCE.md, PROOF.md, SDK_SURFACE.md.</p>
    </div>
  );
}
